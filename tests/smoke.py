"""UI + flow smoke test. Needs: pip install playwright && playwright install chromium
Run from the project root while `python3 -m http.server 8000` is serving it:  python3 tests/smoke.py"""
import sys
from playwright.sync_api import sync_playwright
URL=(sys.argv[1] if len(sys.argv)>1 else 'http://localhost:8000')+'/index.html?debug'
errs=[]
def check(c,m):
    print(('PASS ' if c else 'FAIL ')+m)
    if not c:errs.append(m)
with sync_playwright() as p:
    b=p.chromium.launch();pg=b.new_page(viewport={'width':960,'height':800})
    pg.on('pageerror',lambda e:errs.append('pageerror: '+str(e)))
    pg.on('requestfailed',lambda r:'fonts.googleapis' not in r.url and errs.append('request failed: '+r.url))
    pg.on('response',lambda r:r.status>=400 and errs.append('HTTP %d %s'%(r.status,r.url)))
    pg.goto(URL);pg.wait_for_timeout(1000)
    check(pg.evaluate("getComputedStyle(document.getElementById('ov')).display")=='flex','title screen shown')
    pg.click('text=ENTER THE UNWRITTEN');pg.wait_for_timeout(300)
    check(pg.evaluate("BOV.S.mode")=='play' and pg.evaluate("BOV.S.rs.length")==12,'run starts with 12 rooms')
    # clear a fight room -> pick screen -> click a card
    pg.evaluate("(()=>{const S=BOV.S;const i=S.r.nb.findIndex(n=>n);S.r.open=true;S.x=120;S.y=88;if(i==0)S.y=4;else if(i==1)S.y=172;else if(i==2)S.x=4;else S.x=236})()")
    pg.wait_for_timeout(300);check(pg.evaluate("BOV.S.r.t")=='fight','door transition into a fight room')
    pg.evaluate("BOV.S.es.forEach(e=>e.hp=0)");pg.wait_for_timeout(1200)
    check(pg.evaluate("BOV.S.mode")=='pick','Binding choice opens after clearing')
    pg.click('.card >> nth=0');pg.wait_for_timeout(200)
    check(pg.evaluate("BOV.S.own.length")==1 and pg.evaluate("BOV.S.mode")=='play','clicking a card grants a Binding')
    # keyboard pick path
    pg.evaluate("(()=>{const S=BOV.S;S.r.clr=0;S.r.open=false})()")
    pg.evaluate("BOV.S.es.forEach(e=>e.hp=0)");pg.wait_for_timeout(1200)
    pg.keyboard.press('1');pg.wait_for_timeout(200)
    check(pg.evaluate("BOV.S.own.length")==2,'key 1 picks a Binding')
    # boss win -> stairs
    pg.evaluate("(()=>{const S=BOV.S;S.won=1;S.r=S.rs[0];S.x=120;S.y=56})()");pg.wait_for_timeout(300)
    check(pg.evaluate("BOV.S.mode")=='stairs' and 'STAIRS' in pg.inner_text('#ov'),'stairs screen opens')
    pg.click('text=KEEP EXPLORING');pg.wait_for_timeout(200)
    check(pg.evaluate("BOV.S.mode")=='play','KEEP EXPLORING resumes')
    pg.evaluate("BOV.S.hp=1;BOV.S.iv=0;BOV.S.es.push({t:'skull',x:BOV.S.x,y:BOV.S.y,hp:3,r:6,sp:0,fl:0,tm:1,dir:0,aw:0,st:0,ect:0,vx:0,vy:0,al:1})");pg.wait_for_timeout(2500)
    check(pg.evaluate("BOV.S.mode")=='dead' and 'UNWRITTEN' in pg.inner_text('#ov'),'death screen')
    pg.keyboard.press('r');pg.wait_for_timeout(300)
    check(pg.evaluate("BOV.S.mode")=='play' and pg.evaluate("BOV.S.own.length")==0,'R restarts a fresh run')
    saved=pg.evaluate("JSON.parse(localStorage.getItem('bov1'))");check('d' in saved and 'c' in saved and 'w' in saved,'save data written to key bov1: '+str(saved))
    # ---- keyboard-only controls + victory handling (fresh page/profile)
    pg2=b.new_context(viewport={'width':960,'height':800}).new_page();pg2.on('pageerror',lambda e:errs.append('pageerror: '+str(e)))
    pg2.goto(URL);pg2.wait_for_timeout(800)
    pg2.keyboard.press('Enter');pg2.wait_for_timeout(300)
    check(pg2.evaluate("BOV.S&&BOV.S.mode")=='play','Enter starts a run from the title (no mouse)')
    pg2.evaluate("BOV.S.es=[];BOV.S.r.open=true")
    ang=lambda:pg2.evaluate("BOV.S.aimA");shots=lambda:pg2.evaluate("BOV.S.sh_.map(b=>[b.vx,b.vy])")
    import math
    pg2.keyboard.down('ArrowLeft');pg2.wait_for_timeout(150);pg2.keyboard.up('ArrowLeft');pg2.wait_for_timeout(100)
    check(abs(abs(ang())-math.pi)<1e-6,'ArrowLeft stores aim angle (pi); releasing keeps it: %.3f'%ang())
    pg2.evaluate("BOV.S.sh_=[];BOV.S.fd=0")
    pg2.keyboard.down(' ');pg2.wait_for_timeout(500);pg2.keyboard.up(' ')
    sh=shots();check(len(sh)>=2 and all(v[0]<0 and abs(v[1])<1e-6 for v in sh),'Space fires continuously along stored aim (left): %d shots'%len(sh))
    pg2.keyboard.down('ArrowUp');pg2.keyboard.down('ArrowRight');pg2.wait_for_timeout(120);pg2.keyboard.up('ArrowUp');pg2.keyboard.up('ArrowRight')
    check(abs(ang()+math.pi/4)<1e-6,'Up+Right diagonal aim stored (-pi/4)')
    pg2.keyboard.down('d');pg2.wait_for_timeout(100);pg2.keyboard.up('d')
    check(abs(ang()+math.pi/4)<1e-6,'WASD movement does not change stored aim')
    pg2.evaluate("BOV.S.sh_=[];BOV.S.fd=0");pg2.keyboard.down('ArrowDown');pg2.wait_for_timeout(200);pg2.keyboard.up('ArrowDown')
    sh=shots();check(len(sh)>=1 and all(v[1]>0 and abs(v[0])<1e-6 for v in sh),'ArrowDown fires straight down')
    pg2.mouse.move(700,300);pg2.wait_for_timeout(150)
    check(-1.4<ang()<0 and pg2.evaluate("BOV.S.ak")==0,'moving the mouse hands aim to the mouse (cursor is up-right of player; angle %.2f)'%ang())
    pg2.evaluate("BOV.S.sh_=[];BOV.S.fd=0");pg2.mouse.down();pg2.wait_for_timeout(250);pg2.mouse.up()
    sh=shots();check(len(sh)>=1 and all(v[0]>0 for v in sh),'mouse click still fires toward the cursor')
    pg2.keyboard.down('ArrowUp');pg2.wait_for_timeout(100);pg2.keyboard.up('ArrowUp')
    pg2.evaluate("BOV.S.sh_=[];BOV.S.fd=0");pg2.keyboard.down(' ');pg2.wait_for_timeout(300);pg2.keyboard.up(' ')
    sh=shots();check(len(sh)>=1 and all(v[1]<0 and abs(v[0])<1e-6 for v in sh),'after arrows, Space ignores the mouse position')
    # victory: pool is empty before the first win, boss win counts once, unlocks appear
    pg2.evaluate("BOV.S.own=BOV.S.own.concat([])");check(pg2.evaluate("BOV.SV.w")==0,'victory counter starts at 0')
    boss="(()=>{const S=BOV.S;S.es=[];S.r=S.rs.find(r=>r.t=='boss');S.r.clr=false;S.r.open=false;S.mode='play'})()"
    pg2.evaluate(boss);pg2.wait_for_timeout(300)
    check(pg2.evaluate("BOV.SV.w")==1 and pg2.evaluate("BOV.S.won")==1,'boss victory: counter 0 -> 1, S.won set')
    pg2.evaluate("(()=>{const S=BOV.S;S.r.clr=false;S.es=[];S.mode='play'})()");pg2.wait_for_timeout(300)
    check(pg2.evaluate("BOV.SV.w")==1,'a second clear check in the same run does not double count')
    check(pg2.evaluate("JSON.parse(localStorage.getItem('bov1')).w")==1,'persisted victory count is 1')
    pg2.evaluate("async()=>{const bd=await import('/src/bindings.js');const S=BOV.S;S.mode='play';S.own=bd.BD.map(b=>b.id).filter(i=>i!='pin'&&i!='curse')}")
    pg2.evaluate("(()=>{BOV.S.r.clr=false;BOV.S.r=BOV.S.rs.find(r=>r.t=='fight');BOV.S.es=[];BOV.S.r.open=false;BOV.S.r.clr=false})()");pg2.wait_for_timeout(1300)
    names=sorted(pg2.eval_on_selector_all('.card b','e=>e.map(x=>x.textContent)'));check(names==['Binding of Bugs','Binding of Rebound'],'Rebound + Bugs (old Pinball Law / Bug Report) unlocked after the win: %s'%names)
    pg2.keyboard.press('Escape');pg2.wait_for_timeout(150)
    pg2.evaluate("(()=>{const S=BOV.S;S.r=S.rs[0];S.x=120;S.y=56})()");pg2.wait_for_timeout(300)
    check(pg2.evaluate("BOV.S.mode")=='stairs','stairs still work after victory')
    pg2.keyboard.press('Enter');pg2.wait_for_timeout(200)
    check(pg2.evaluate("BOV.S.mode")=='play' and pg2.evaluate("BOV.SV.w")==1,'Enter = KEEP EXPLORING; stairs do not touch the counter')
    pg2.evaluate("(()=>{const S=BOV.S;S.x=120;S.y=56;S.won=1})()");pg2.wait_for_timeout(100);pg2.keyboard.press('r');pg2.wait_for_timeout(300)
    check(pg2.evaluate("BOV.S.won||0")==0 and pg2.evaluate("BOV.S.own.length")==0,'R on the stairs screen starts a new run')
    pg2.evaluate(boss);pg2.wait_for_timeout(300)
    check(pg2.evaluate("BOV.SV.w")==2,'second run boss victory: counter 1 -> 2 (once per victory)')
    b.close()
print('\n'+('ALL PASSED' if not errs else 'PROBLEMS:\n'+'\n'.join(errs)));sys.exit(1 if errs else 0)
